SELECT b.AUTHOR_ID, a.AUTHOR_NAME, b.CATEGORY, SUM(b.SALES * b.PRICE) AS TOTAL_SALES
FROM AUTHOR a
JOIN (SELECT b.BOOK_ID, bs.SALES, b.CATEGORY, b.AUTHOR_ID, b.PRICE, bs.SALES_DATE
      FROM BOOK b
      JOIN BOOK_SALES bs ON bs.BOOK_ID = b.BOOK_ID
) b
ON a.AUTHOR_ID = b.AUTHOR_ID
WHERE b.SALES_DATE >= '2022-01-01' AND b.SALES_DATE <= '2022-01-31'
GROUP BY b.AUTHOR_ID, a.AUTHOR_NAME, b.CATEGORY
ORDER BY b.AUTHOR_ID ASC, b.CATEGORY DESC